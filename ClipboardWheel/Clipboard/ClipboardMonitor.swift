import AppKit

/// Watches the system clipboard and records new copies on the wheel.
///
/// macOS has no "clipboard changed" notification, so this checks the clipboard's change
/// count a few times a second. Checking the count doesn't read anything.
final class ClipboardMonitor {
    /// What a copy turned into.
    enum Content: Equatable {
        case text(String)
        case image(pngData: Data)
    }

    enum Kind: Equatable {
        case text
        case image
    }

    /// Markers that password managers and similar apps add to say "don't save this".
    /// See nspasteboard.org.
    static let privateMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    static let imageTypes: Set<NSPasteboard.PasteboardType> = [
        .png, .tiff, NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("public.heic"),
    ]

    /// Ignore enormous text (over about a million characters).
    static let maxTextLength = 1_000_000

    var isPaused = false

    private let clipboard: ClipboardModel
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?

    init(clipboard: ClipboardModel) {
        self.clipboard = clipboard
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Skips a clipboard change the app made itself (pasting from the wheel).
    func ignore(changeCount: Int) {
        ignoredChangeCount = changeCount
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard changeCount != ignoredChangeCount, !isPaused else { return }

        switch Self.readContent(from: pasteboard) {
        case let .text(text): clipboard.recordText(text)
        case let .image(pngData): clipboard.recordImage(pngData: pngData)
        case nil: break
        }
    }

    // MARK: - Reading the clipboard

    /// Decides whether a copy should be treated as text, an image, or skipped, from the
    /// clipboard's types alone (in the order the copying app listed them).
    static func preferredKind(for types: [NSPasteboard.PasteboardType]) -> Kind? {
        let names = Set(types.map(\.rawValue))
        guard names.isDisjoint(with: privateMarkerTypes) else { return nil }
        if types.contains(.fileURL) { return nil } // files copied in Finder aren't supported
        let hasText = types.contains(.string)
        let hasImage = types.contains { imageTypes.contains($0) }
        // Apps list their best format first. Word, for example, adds a picture of copied
        // text, but lists the text first; a browser's "Copy Image" lists the image first.
        if hasImage, let first = types.first, imageTypes.contains(first) { return .image }
        if hasText { return .text }
        if hasImage { return .image }
        return nil
    }

    static func readContent(from pasteboard: NSPasteboard) -> Content? {
        switch preferredKind(for: pasteboard.types ?? []) {
        case .text:
            guard let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  text.utf16.count <= maxTextLength
            else { return nil }
            return .text(text)
        case .image:
            if let png = pasteboard.data(forType: .png) { return .image(pngData: png) }
            guard let png = NSImage(pasteboard: pasteboard)?.pngData() else { return nil }
            return .image(pngData: png)
        case nil:
            return nil
        }
    }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
